ALTER TABLE users ADD COLUMN xp BIGINT NOT NULL DEFAULT 0 CHECK (xp >= 0);
CREATE TABLE card_acquisitions (
    id BIGSERIAL PRIMARY KEY,
    opening_id UUID NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    card_id TEXT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    rarity TEXT,
    xp_each INTEGER NOT NULL DEFAULT 0 CHECK (xp_each >= 0),
    source TEXT NOT NULL,
    telegram_update_id BIGINT,
    received_at TIMESTAMPTZ, -- NULL for estimated baseline; never invent an acquisition time.
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (opening_id, card_id)
);
CREATE INDEX idx_card_acquisitions_user_time ON card_acquisitions(user_id, recorded_at DESC, id DESC);
CREATE INDEX idx_card_acquisitions_update ON card_acquisitions(telegram_update_id) WHERE telegram_update_id IS NOT NULL;
CREATE UNIQUE INDEX idx_card_acquisitions_draw_update ON card_acquisitions(source,telegram_update_id,card_id)
    WHERE source IN ('pack','free_card') AND telegram_update_id IS NOT NULL;
CREATE TABLE free_card_receipts (
    update_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    card_id TEXT NOT NULL,
    is_new BOOLEAN NOT NULL,
    completed_collection_ids TEXT[] NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_free_card_receipts_user ON free_card_receipts(user_id, created_at DESC);
