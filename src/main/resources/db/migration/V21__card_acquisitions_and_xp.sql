CREATE TEMP TABLE xp_holdings ON COMMIT DROP AS
SELECT user_id, card_id, SUM(quantity)::BIGINT AS quantity FROM (
    SELECT user_id, card_id, quantity FROM user_cards
    UNION ALL SELECT seller_id, card_id, 1 FROM market_listings WHERE status = 'ACTIVE'
    UNION ALL SELECT user_id, card_id, 1 FROM random_trade_pool WHERE status = 'WAITING'
) h GROUP BY user_id, card_id;
CREATE TEMP TABLE xp_receipt_counts ON COMMIT DROP AS
SELECT r.user_id, c.card_id, COUNT(*)::BIGINT AS quantity
FROM pack_opening_receipts r CROSS JOIN LATERAL unnest(r.card_ids) c(card_id)
GROUP BY r.user_id, c.card_id;
DO $$ BEGIN
    IF EXISTS (
        SELECT card_id FROM (SELECT card_id FROM xp_holdings UNION SELECT card_id FROM xp_receipt_counts) ids
        WHERE NOT EXISTS (SELECT 1 FROM xp_catalog_snapshot c WHERE c.card_id = ids.card_id)
    ) THEN RAISE EXCEPTION 'XP backfill contains a card absent from the frozen catalog'; END IF;
END $$;
-- Each surviving pack receipt is an exact historical draw; refunds do not remove it.
INSERT INTO card_acquisitions(opening_id,user_id,card_id,quantity,rarity,xp_each,source,telegram_update_id,received_at)
SELECT md5('legacy_pack:' || r.update_id::TEXT)::UUID, r.user_id, c.card_id, COUNT(*)::INTEGER, s.rarity, s.xp_each,
       'legacy_pack', r.update_id, r.created_at
FROM pack_opening_receipts r CROSS JOIN LATERAL unnest(r.card_ids) c(card_id)
JOIN xp_catalog_snapshot s ON s.card_id = c.card_id
GROUP BY r.update_id,r.user_id,r.created_at,c.card_id,s.rarity,s.xp_each;
-- Per card: max(known pack draws, surviving holdings including escrow), avoiding double counting.
INSERT INTO card_acquisitions(opening_id,user_id,card_id,quantity,rarity,xp_each,source,received_at)
SELECT gen_random_uuid(), h.user_id, h.card_id, (h.quantity - COALESCE(r.quantity,0))::INTEGER,
       s.rarity, s.xp_each, 'legacy_baseline', NULL
FROM xp_holdings h JOIN xp_catalog_snapshot s ON s.card_id = h.card_id
LEFT JOIN xp_receipt_counts r ON r.user_id = h.user_id AND r.card_id = h.card_id
WHERE h.quantity > COALESCE(r.quantity,0);
UPDATE users u SET xp = a.xp FROM (
    SELECT user_id, SUM(quantity::BIGINT * xp_each) AS xp FROM card_acquisitions GROUP BY user_id
) a WHERE u.id = a.user_id;
